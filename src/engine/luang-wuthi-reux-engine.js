    function checkThaiBuayKamphra(horakhun) {
        const rem = (horakhun + 27) % 60;
        const badRemList = [12, 20, 34, 48, 55];
        const isBad = badRemList.includes(rem);
        return {
            horakhun,
            rem,
            isBad,
            desc: isBad ? `ตรงกับ "วันไทยบ่วยกำพร้า" (เศษ ${rem}) แม้เป็นอัมฤตโชคหรือมหาสิทธิโชคก็พึงห้ามเด็ดขาด หากวิวาห์จะหย่าร้าง ปลูกเรือนจะร้าง` : "ไม่ใช่วันไทยบ่วยกำพร้า"
        };
    }

    // บทที่ 2 ข้อ 11: ดิถีอายกรรมพลาย / วันภาณฤกษ์ (หน้า 47-48)
    const AYE_KAMMAPLAI = {
        1: [4, 5, 6], 2: [1, 2, 3], 3: [13, 14, 15], 4: [10, 11, 12],
        5: [2, 3, 4], 6: [3, 4, 5], 7: [4, 5, 6], 8: [1, 2, 3],
        9: [13, 14, 15], 10: [10, 11, 12], 11: [2, 3, 4], 12: [3, 4, 5]
    };

    function checkAyeKammaplai(lunarMonth, lunarDay) {
        const monthRule = AYE_KAMMAPLAI[lunarMonth] || [];
        const isBad = monthRule.includes(lunarDay);
        let stage = "";
        if (lunarDay === monthRule[0]) stage = "ปฐม (จะลำบาก)";
        if (lunarDay === monthRule[1]) stage = "ทุติยะ (จะเป็นอันตราย)";
        if (lunarDay === monthRule[2]) stage = "ตติยะ (จะฉิบหาย)";

        return {
            isBad,
            stage,
            desc: isBad ? `ตรงกับ "ดิถีอายกรรมพลาย" (${stage}) เดือน ${lunarMonth} ห้ามทำการมงคลและยาตรา` : "ไม่ติดดิถีอายกรรมพลาย"
        };
    }

