    // บทที่ 2 ข้อ 9: วันขลุบ - ราศีขลุบ - ฤกษ์ขลุบ (หน้า 45-46)
    function calculateKhlub(yearCS, currentDayNum, currentRasiIdx, currentNakshatraIdx) {
        const base = yearCS + 1120;
        const dayKhlubRem = base % 7;       // 0=เสาร์, 1=อาทิตย์, ...
        const rasiKhlubRem = base % 12;     // 0=มีน, 1=เมษ, ...
        const reuxKhlubRem = base % 27;     // 0=เรวดี(27), 1=อัศวินี(1), ...

        const dayKhlubName = DAY_LIST[dayKhlubRem === 0 ? 6 : dayKhlubRem - 1];
        const rasiKhlubName = RASI_LIST[rasiKhlubRem === 0 ? 11 : rasiKhlubRem - 1];
        const reuxKhlubName = NAKSHATRA_27[reuxKhlubRem === 0 ? 26 : reuxKhlubRem - 1].name;

        const isDayKhlub = (currentDayNum === (dayKhlubRem === 0 ? 7 : dayKhlubRem));
        const isRasiKhlub = ((currentRasiIdx + 1) === (rasiKhlubRem === 0 ? 12 : rasiKhlubRem));
        const isReuxKhlub = (currentNakshatraIdx === (reuxKhlubRem === 0 ? 27 : reuxKhlubRem));

        return {
            base,
            dayKhlubRem,
            dayKhlubName,
            rasiKhlubRem,
            rasiKhlubName,
            reuxKhlubRem,
            reuxKhlubName,
            isDayKhlub,
            isRasiKhlub,
            isReuxKhlub,
            hasKhlub: (isDayKhlub || isRasiKhlub || isReuxKhlub),
            warnings: [
                isDayKhlub ? `ตรงกับ "วันขลุบ" (${dayKhlubName}) เจ้าการจะถึงแก่ความตายจริง พึงห้ามเด็ดขาด` : null,
                isRasiKhlub ? `ตรงกับ "ราศีขลุบ" (${rasiKhlubName}) บริวารข้าคนจะฉิบหายล้มตาย` : null,
                isReuxKhlub ? `ตรงกับ "ฤกษ์ขลุบ" (${reuxKhlubName}) ลูกเมียจะตาย ปลูกเรือนฟ้าจะผ่า แต่งงานพลัดพราก` : null
            ].filter(Boolean)
        };
    }

