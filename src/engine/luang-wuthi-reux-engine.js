    // ฟังก์ชันหาศัตรูใหญ่ และ ศัตรูน้อย ของวันใดๆ (เช่น วันของฤกษ์ปัจจุบัน)
    function getDayEnemiesOfCurrentDay(dayName) {
        if (!dayName) return { bigEnemies: [], smallEnemies: [] };
        const bigEnemies = [];
        BIG_ENEMY_PAIRS.forEach(pair => {
            if (pair[0] === dayName) bigEnemies.push(pair[1]);
            else if (pair[1] === dayName) bigEnemies.push(pair[0]);
        });

        // ศัตรูน้อย: วันที่มอง dayName เป็นศัตรู หรือ dayName มองเป็นศัตรู
        const smallEnemiesSet = new Set();
        // 1. วันที่ dayName เป็นศัตรูด้วย
        if (SMALL_ENEMY_MAP[dayName]) {
            SMALL_ENEMY_MAP[dayName].forEach(e => smallEnemiesSet.add(e));
        }
        // 2. วันที่มอง dayName เป็นศัตรู
        for (const [k, list] of Object.entries(SMALL_ENEMY_MAP)) {
            if (list.includes(dayName)) {
                smallEnemiesSet.add(k);
            }
        }
        // นำศัตรูใหญ่ออกเพื่อความชัดเจน
        bigEnemies.forEach(b => smallEnemiesSet.delete(b));

        return {
            dayName,
            bigEnemies,
            smallEnemies: Array.from(smallEnemiesSet)
        };
    }

