    function calculateDailyCutReuxSchedule(targetDate) {
        const startOfDay = new Date(targetDate);
        startOfDay.setHours(0, 0, 0, 0);

        function getExactMoonLong(dObj) {
            const y = dObj.getFullYear(), m = dObj.getMonth() + 1, d = dObj.getDate();
            const h = dObj.getHours() + dObj.getMinutes() / 60 + dObj.getSeconds() / 3600;
            let jy = y, jm = m;
            if (m <= 2) { jy -= 1; jm += 12; }
            const A = Math.floor(jy / 100);
            const B = 2 - A + Math.floor(A / 4);
            const jd = Math.floor(365.25 * (jy + 4716)) + Math.floor(30.6001 * (jm + 1)) + d + (h - 7) / 24 + B - 1524.5;
            const dJ2000 = jd - 2451545.0;
            const ayanamsa = 24.12;
            let l = (218.316 + 13.176396 * dJ2000 + 6.289 * Math.sin(0.01745 * (134.963 + 13.064993 * dJ2000)) - ayanamsa) % 360;
            if (l < 0) l += 360;
            return l;
        }

        const timeline = [];
        const nakSpan = 360 / 27; // 13.3333333333°
        const padaSpan = 360 / 108; // 3.3333333333°

        let prevNakIdx = -1;
        let prevPada = -1;
        let periodStartMinute = 0;

        for (let m = 0; m <= 1440; m += 5) {
            const curTime = new Date(startOfDay.getTime() + m * 60000);
            const l = getExactMoonLong(curTime);
            const nakIdx = (Math.floor(l / nakSpan) % 27) + 1;
            const pada = (Math.floor((l % nakSpan) / padaSpan) % 4) + 1;

            if (m === 0) {
                prevNakIdx = nakIdx;
                prevPada = pada;
                periodStartMinute = 0;
            } else {
                const isNakCut = (nakIdx !== prevNakIdx);
                const isPadaCut = (pada !== prevPada && !isNakCut);

                if (isNakCut || isPadaCut || m === 1440) {
                    const startH = String(Math.floor(periodStartMinute / 60)).padStart(2, '0');
                    const startM = String(periodStartMinute % 60).padStart(2, '0');
                    const endH = String(Math.floor(m / 60)).padStart(2, '0');
                    const endM = String(m % 60).padStart(2, '0');

                    const curNak = NAKSHATRA_27[prevNakIdx - 1];
                    const nextNak = NAKSHATRA_27[nakIdx - 1];

                    timeline.push({
                        period: `${startH}:${startM} - ${endH}:${endM} น.`,
                        startMinute: periodStartMinute,
                        endMinute: m,
                        cutTime: `${endH}:${endM} น.`,
                        nakshatra: curNak,
                        nakshatraIdx: prevNakIdx,
                        pada: prevPada,
                        group: curNak.group,
                        cutType: isNakCut ? "ตัดฤกษ์ใหญ่ (เปลี่ยนนักษัตร)" : (isPadaCut ? "ตัดบาทฤกษ์ (เปลี่ยนลูกนวางค์)" : "สิ้นสุดวัน"),
                        isNakCut,
                        isPadaCut,
                        nextNakshatra: nextNak,
                        nextPada: pada,
                        nextGroup: nextNak.group,
                        meaning: REUX_GROUP_DETAILS[curNak.group] ? REUX_GROUP_DETAILS[curNak.group].nature : "",
                        isAuspicious: !["โจโร", "เพชฌฆาต"].includes(curNak.group)
                    });

                    prevNakIdx = nakIdx;
                    prevPada = pada;
                    periodStartMinute = m;
                }
            }
        }

        return timeline;
    }
